// Generates icons/icon{16,32,48,128}.png and shared/logo.js from the logo (SVG preferred, PNG works too).
// Not part of the extension; needs the `sharp` package, installed outside this repo:
//   mkdir /tmp/sharp && cd /tmp/sharp && npm init -y && npm i sharp
//   NODE_PATH=/tmp/sharp/node_modules node tools/make-icons.js path/to/logo.svg
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const src = process.argv[2];
if (!src) { console.error('usage: make-icons.js <logo.svg|logo.png>'); process.exit(1); }
const outDir = path.join(__dirname, '..', 'icons');

(async () => {
  for (const size of [16, 32, 48, 128]) {
    await sharp(src, { density: 600 })
      .trim({ threshold: 10 })
      .resize(size, size, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
      .png()
      .toFile(path.join(outDir, `icon${size}.png`));
    console.log('icons/icon' + size + '.png');
  }
  // Inline copy of the logo for the in-page button (avoids exposing icons to web pages).
  const png = fs.readFileSync(path.join(outDir, 'icon32.png')).toString('base64');
  fs.writeFileSync(path.join(__dirname, '..', 'shared', 'logo.js'),
    '// Generated by tools/make-icons.js. Do not edit.\nself.PassmanLogo = \'data:image/png;base64,' + png + '\';\n');
  console.log('shared/logo.js');
})();
